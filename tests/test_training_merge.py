def test_the_modelfile_keeps_the_base_template_and_points_at_the_merged_folder(tmp_path):
    text = train_export.merged_modelfile(BASE_MODELFILE, tmp_path / "merged")
    lines = text.splitlines()
    assert lines[0] == f"FROM {(tmp_path / 'merged').resolve()}"
    assert "sha256-abc" not in text and not any(l.startswith("#") for l in lines)
    assert "FROM inside the template stays" in text
    assert text.count("PARAMETER stop") == 2 and "TEMPLATE" in text and "LICENSE" in text


def _registry(tmp_path, monkeypatch, adapter_sha="a" * 64, merge_sha="a" * 64):
    merged = tmp_path / "merged"
    merged.mkdir()
    (merged / "merge.json").write_text(json.dumps({"adapter_sha256": merge_sha}), encoding="utf-8")
    monkeypatch.setattr(train_export.ep, "load_candidate", lambda _d: {"adapter_sha256": adapter_sha})
    calls, seen = [], {}

    def run(cmd, **_kw):
        calls.append(cmd)
        if cmd[1] == "show":
            return types.SimpleNamespace(returncode=0, stdout=BASE_MODELFILE, stderr="")
        seen["modelfile"] = Path(cmd[cmd.index("-f") + 1]).read_text(encoding="utf-8")
        return types.SimpleNamespace(returncode=0, stdout="success", stderr="")

    monkeypatch.setattr(train_export.subprocess, "run", run)
    registry = train_export.MergedRegistry(merged, "http://127.0.0.1:11434", binary="ollama")
    return registry, calls, seen, merged


def test_register_imports_the_merged_folder_quantised_only_when_asked(tmp_path, monkeypatch):
    registry, calls, seen, merged = _registry(tmp_path, monkeypatch)
    registry.create_from_adapter("orion-planner:loc-x", "llama3.2:3b", tmp_path / "cand" / "adapter")
    create = calls[-1]
    assert create[:3] == ["ollama", "create", "orion-planner:loc-x"] and "--quantize" not in create
    assert seen["modelfile"].startswith(f"FROM {merged.resolve()}")
    assert "ADAPTER" not in seen["modelfile"]
    registry.quantize = "int4"
    registry.create_from_adapter("orion-planner:loc-y", "llama3.2:3b", tmp_path / "cand" / "adapter")
    assert calls[-1][-2:] == ["--quantize", "int4"]


def test_a_gguf_in_the_merged_folder_is_imported_as_it_stands(tmp_path, monkeypatch):
    registry, calls, seen, merged = _registry(tmp_path, monkeypatch)
    (merged / "model-q8_0.gguf").write_bytes(b"GGUF")
    registry.quantize = "int4"                          # never applied to a GGUF import
    registry.create_from_adapter("orion-planner:loc-x", "llama3.2:3b", tmp_path / "cand" / "adapter")
    assert "--quantize" not in calls[-1]
    assert seen["modelfile"].startswith(f"FROM {(merged / 'model-q8_0.gguf').resolve()}")


def test_a_failed_create_reports_its_error_line(tmp_path, monkeypatch):
    registry, _calls, _seen, _merged = _registry(tmp_path, monkeypatch)
    monkeypatch.setattr(train_export.subprocess, "run", lambda cmd, **_kw: types.SimpleNamespace(
        returncode=0 if cmd[1] == "show" else 1, stdout=BASE_MODELFILE if cmd[1] == "show" else "",
        stderr="\x1b[?25l\rimporting\rError: MLX runtime is not available: failed to load (searched: [a b c])"))
    with pytest.raises(train_export.ep.PromotionRefused, match="MLX runtime is not available"):
        registry.create_from_adapter("orion-planner:loc-x", "llama3.2:3b", tmp_path / "cand" / "adapter")


def test_a_merged_model_from_another_adapter_is_refused(tmp_path, monkeypatch):
    registry, calls, _seen, _merged = _registry(tmp_path, monkeypatch, merge_sha="b" * 64)
    with pytest.raises(train_export.ep.PromotionRefused, match="different adapter"):
        registry.create_from_adapter("orion-planner:loc-x", "llama3.2:3b", tmp_path / "cand" / "adapter")
    assert calls == []


def _candidate(tmp_path, *, tamper=False):
    cand = tmp_path / "cand"
    (cand / "adapter").mkdir(parents=True)
    weights = cand / "adapter" / "adapter_model.safetensors"
    weights.write_bytes(b"weights")
    digest = hashlib.sha256(b"weights").hexdigest()
    (cand / "candidate.json").write_text(json.dumps({
        "candidate_id": "loc-x", "adapter_sha256": digest, "base_model_id": "b",
        "files": {"adapter/adapter_model.safetensors": digest}}), encoding="utf-8")
    if tamper:
        weights.write_bytes(b"changed")
    return cand


def test_merge_refuses_a_changed_adapter_before_loading_anything(tmp_path):
    with pytest.raises(train_lora.Refused, match="changed since it was trained"):
        train_lora.merge_candidate(_candidate(tmp_path, tamper=True), tmp_path / "base", tmp_path / "out")


def test_merge_refuses_a_missing_base_or_an_existing_destination(tmp_path):
    cand = _candidate(tmp_path)
    with pytest.raises(train_lora.Refused, match="base model"):
        train_lora.merge_candidate(cand, tmp_path / "nobase", tmp_path / "out")
    base = tmp_path / "base"
    base.mkdir()
    (base / "config.json").write_text("{}", encoding="utf-8")
    (base / "model.safetensors").write_bytes(b"x")
    (base / "tokenizer.json").write_text("{}", encoding="utf-8")
    (tmp_path / "out").mkdir()
    with pytest.raises(train_lora.Refused, match="already exists"):
        train_lora.merge_candidate(cand, base, tmp_path / "out")


