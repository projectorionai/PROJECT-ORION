"""
Everyday requests for EVERY tool — the evaluation set for ORION's intent routing.

``tool_routing_cases.py`` (75 phrases, ~30 tools) decides whether the resolver
may filter at all. This set measures how well the whole ranking — words,
meaning and the learned intent network — puts the right tool first, across
every capability ORION declares (find_tool and use_tool excepted: nobody asks
for the gateway by name).

Written 2026-09-28 against each tool's purpose, in ordinary British speech:
plain asks, indirect needs ("do I need a coat today" -> geo), speech and
typing slips ("remnd me to take my tablets") and multi-step asks. Each case
names the right tool and any OTHER tool that would also be a right answer, so
a genuine ambiguity is not scored as a miss. No phrase is copied from a tool
description, a quoted example or the vocabulary; a test checks that
mechanically (no four-word run shared with any of them).

The previous set of this kind (376 requests, 2026-09-26) lived only in a
scratch folder and was lost, so those figures could not be reproduced. This
one is kept with the tests on purpose.

Split by index, as the golden set is: the even half may be inspected while
choosing settings, the odd half is the honest score and is never looked at
case by case while tuning.
"""

