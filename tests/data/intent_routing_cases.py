CASES: list[Case] = PLAIN + INDIRECT + SLIPS + MULTI


def kind_of(case: Case) -> str:
    for name, group in (("plain", PLAIN), ("indirect", INDIRECT), ("slip", SLIPS),
                        ("multi", MULTI)):
        if case in group:
            return name
    return "plain"


def acceptable(case: Case) -> set[str]:
    return {case[1], *case[2]}


def dev_cases() -> list[Case]:
    """Even indices — the half that may be inspected while tuning."""
    return [c for i, c in enumerate(CASES) if i % 2 == 0]


def holdout_cases() -> list[Case]:
    """Odd indices — never inspected while tuning; the honest score."""
    return [c for i, c in enumerate(CASES) if i % 2 == 1]


